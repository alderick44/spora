      <h2 class="h5 mt-5">Deux règles avant tout le reste</h2>

      <p>Ne les lavez pas à grande eau. Les champignons absorbent l'eau comme des éponges, et toute cette eau finit ensuite dans votre poêle. Un coup de brosse ou un linge humide suffit.</p>

      <p>Ne les entassez pas. C'est l'erreur la plus courante. Quand la poêle est trop pleine, les champignons bouillent dans leur propre eau au lieu de colorer, et ils sortent gris et caoutchouteux. Faites-les en deux fois à feu vif. Salez seulement à la fin, parce que le sel les fait dégorger trop tôt.</p>

      <h2 class="h5 mt-5">Le pleurote en huître</h2>

      <p>Le pleurote cuit vite et il est fragile. Sa chair est mince, elle rend beaucoup d'eau, et ensuite elle colore très rapidement. Il faut le surveiller.</p>

      <p>Il se défait si on le fait mijoter trop longtemps. Dans une soupe ou une sauce, ajoutez-le à la fin plutôt qu'au début. Il se déchire tout seul dans le sens des lamelles, vous n'avez pas besoin de couteau.</p>

      <h2 class="h5 mt-5">Le strophaire</h2>

      <p>Le strophaire est plus ferme et plus charnu que le pleurote. C'est celui qui supporte la cuisson longue. Braisé ou mijoté, il garde sa forme là où le pleurote aurait disparu.</p>

      <p>Cueilli jeune, avant que le chapeau s'ouvre, il est ferme et le pied est aussi bon que le chapeau. Passé ce stade il devient spongieux. Les gros chapeaux se tranchent épais et se cuisinent presque comme une pièce de viande.</p>

      <p>Il faut le manger bien cuit. Ce n'est pas un champignon à manger cru.</p>

      <h2 class="h5 mt-5">Conservation</h2>

      <p>Ils se congèlent mieux cuits que crus. Passez-les à la poêle avant de les mettre au congélateur et ils vont garder leur texture.</p>

